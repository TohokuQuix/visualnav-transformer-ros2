"""Selection contract for the existing five-row Onix terrain generator."""

from __future__ import annotations

TERRAIN_TYPES = (
    "k_rail_step_field", "pyramid_stairs", "pyramid_stairs_inv",
    "random_rough", "boxes", "hf_pyramid_slope", "k_rail_field",
)


def terrain_band(level: int, difficulty_range: tuple[float, float]) -> tuple[float, float]:
    """Isaac Lab curriculum row's actual difficulty interval, upper bound exclusive."""
    if level not in range(5):
        raise ValueError("terrain level must be 0..4")
    lower, upper = map(float, difficulty_range)
    if not lower < upper:
        raise ValueError("invalid terrain difficulty range")
    width = (upper - lower) / 5
    return lower + level * width, lower + (level + 1) * width


def configure_selected_terrain(generator, importer, terrain_type: str, level: int, num_envs: int) -> dict:
    """Use original sub-terrain parameters; select one curriculum row and one type.

    The 5×N grid is generated by Isaac Lab. One env occupies the selected row;
    N=4 keeps the optional four-robot mode on four distinct tiles.
    """
    if terrain_type not in TERRAIN_TYPES or terrain_type not in generator.sub_terrains:
        raise ValueError(f"unsupported terrain type: {terrain_type}")
    if num_envs not in (1, 4):
        raise ValueError("demo supports 1 or 4 envs")
    band = terrain_band(level, generator.difficulty_range)
    generator.num_rows = 5
    generator.num_cols = num_envs
    generator.curriculum = True
    generator.use_cache = False
    generator.sub_terrains = {terrain_type: generator.sub_terrains[terrain_type]}
    generator.sub_terrains[terrain_type].proportion = 1.0
    importer.max_init_terrain_level = level
    importer.eat_nav_selected_level = level
    return {"terrain_type": terrain_type, "terrain_level": level,
            "difficulty_band": band, "difficulty_range": tuple(generator.difficulty_range),
            "grid_rows": 5, "grid_cols": num_envs}
